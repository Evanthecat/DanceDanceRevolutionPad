#define ANIMATION_DELAY 500

uint16_t timer = 0;
uint16_t frame = 0;

static void playAnimation(void) {
    if (timer_elapsed(timer) > ANIMATION_DELAY) {
        oled_set_cursor(108, 41);
        oled_write_raw_P(ghostBuffer[frame], sizeof(ghost1));

        oled_set_cursor(95, 12);
        oled_write_raw_P(catBuffer[frame], sizeof(cat1));

        oled_set_cursor(77, 3);
        oled_write_raw_P(pacmanBuffer[frame], sizeof(pacman1));

        oled_set_cursor(7, 18);
        oled_write_raw_P(sBuffer[frame], sizeof(s1));

        oled_set_cursor(30, 9);
        oled_write_raw_P(bunnyBuffer[frame], sizeof(bunny1));

        oled_set_cursor(53, 11);
        if (upPressed) {
            oled_write_raw_P(upPressedBuffer[frame], sizeof(upPressed1));
        }
        else {
            oled_write_raw_P(upUnpressedBuffer[frame], sizeof(upUnpressed1));
        }

        oled_set_cursor(55, 31);
        if (downPressed) {
            oled_write_raw_P(downPressedBuffer[frame], sizeof(downPressed1));
        }
        else {
            oled_write_raw_P(downUnpressedBuffer[frame], sizeof(downUnpressed1));
        }

        oled_set_cursor(36, 29);
        if (leftPressed) {
            oled_write_raw_P(leftPressedBuffer[frame], sizeof(leftPressed1));
        }
        else {
            oled_write_raw_P(leftUnpressedBuffer[frame], sizeof(leftUnpressed1));
        }

        oled_set_cursor(78, 29);
        if (rightPressed) {
            oled_write_raw_P(rightPressedBuffer[frame], sizeof(rightPressed1));
        }
        else {
            oled_write_raw_P(rightUnpressedBuffer[frame], sizeof(rightUnpressed1));
        }

        if (frame == 3) {
            frame = 0;
        }
        else {
            frame++;
        }
    }
}

bool oled_task_user(void) {
    playAnimation();
    return false;
}

